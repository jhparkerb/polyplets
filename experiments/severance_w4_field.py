#!/usr/bin/env python3
"""Severance W4, Phase 0: are depths 2, 3 degree-4 algebraic on depth 1's curve?

Hypothesis (generalizing severance_w2_kernel.py's depth-1 result): every
below-onset depth-j defect GF  F_j(y) = sum_k D_j(k) y^k  lies in the SINGLE
biquadratic field  K = Q(s)[A,B]  (y = s^2), with

    A^2 = 1 - 2s - 3s^2 = (1-3s)(1+s),   B^2 = 1 + 2s - 3s^2 = (1+3s)(1-s).

Membership in K is equivalent to: F_j is algebraic over Q(y) of degree <= 4,
with V4 (biquadratic) Galois group and the two quadratic subfields generated by
A and B.  This script tests the two necessary, computable fingerprints for
j = 2, 3, reusing the PROVEN depth-1 fitter of experiments/depth1_minpoly.py:

  (1) DEGREE.  A mod-p dimension scan finds the minimal box (deg_y, deg_W) of an
      algebraic relation Phi_j(y, W) = 0, holdout-verified past the fit rows.
      Membership in K forces deg_W <= 4.  (depth 1 lands at (8,4).)

  (2) BRANCH LOCUS.  Solve Phi_j exactly over Q; its W-leading coefficient and
      W-discriminant must be supported only on the depth-1 branch factors --
      the roots of (1-2s-3s^2)(1+2s-3s^2) together with the kernel's
      3+S pole, i.e. in y: factors of (1-9y)(1-y) and the shared 27x-1 = 9y-1.
      A branch anywhere else would put F_j outside K.

Calibration (verifier held above the claim): stage C runs depth 1 through the
same pipeline and asserts it reproduces the known (8,4) box and the published
Phi_1 leading factor (27x-1)^2 (= (9y-1)^2 after y=3x).

Run from repo root:  python3 -u experiments/severance_w4_field.py [KMAX]
"""
import os
import sys
import time
from fractions import Fraction as Fr

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from severance_w3_depths import D_series                              # noqa: E402
from severance_w3_modp import Dj_mod                                  # noqa: E402
from depth1_minpoly import (powers_of_series, relation_rows,          # noqa: E402
                            check_relation)
from depth1_asymptotics import modp_nullspace                         # noqa: E402

PRIME = (1 << 61) - 1


def Dj_exact_int(j, K):
    """D_j(k) over Q cleared to integers by one constant 3^M (M = max v3 denom).

    A uniform constant multiple leaves the algebraic relation's box and its
    W-leading factor unchanged (up to constant), so it is safe for the branch
    fingerprint.  Only called at the box-finding K, never at the scan K."""
    D = D_series(j, K)
    M = max(D[k].denominator.bit_length() for k in range(K + 1))  # loose upper
    # denominators are pure powers of 3; find the exact max exponent
    def v3(n):
        c = 0
        while n % 3 == 0:
            n //= 3
            c += 1
        return c
    M = max(v3(D[k].denominator) for k in range(K + 1))
    scale = 3 ** M
    return [int(D[k] * scale) for k in range(K + 1)]


def minbox_scan(Np, K, fit_hi, dy_range, dF_range):
    """mod-p: smallest (dy,dF) with a holdout-surviving relation. Returns list.

    Np is the series ALREADY reduced mod PRIME (field elements)."""
    powp = powers_of_series(Np, max(dF_range), K, PRIME)
    found = []
    for dF in dF_range:
        line = []
        for dy in dy_range:
            if fit_hi + 1 < (dy + 1) * (dF + 1):
                line.append("-")
                continue
            rows = relation_rows(powp, dy, dF, range(fit_hi + 1))
            ns = modp_nullspace(rows, PRIME)
            good = [v for v in ns
                    if check_relation(v, powp, dy, dF,
                                      range(fit_hi + 1, K + 1), PRIME)
                    and any(v[idx] for idx in range((dy + 1), len(v)))]
            line.append(len(good))
            if good:
                found.append((dy, dF, len(good)))
        print(f"   deg_W={dF}: deg_y {list(dy_range)} -> "
              f"[{', '.join(map(str, line))}]", flush=True)
    return found


def exact_solve(N, K, dy, dF):
    """Exact minimal polynomial coeffs (list of length (dy+1)*(dF+1)) over Q."""
    powx = powers_of_series(N, dF, K)
    nunk = (dy + 1) * (dF + 1)
    orders = range(0, nunk + 12)
    M = [[Fr(x) for x in r] for r in relation_rows(powx, dy, dF, orders)]
    # rational nullspace via Gaussian elimination
    nrow, piv = len(M), {}
    r = 0
    for c in range(nunk):
        sel = next((i for i in range(r, nrow) if M[i][c] != 0), None)
        if sel is None:
            continue
        M[r], M[sel] = M[sel], M[r]
        inv = M[r][c]
        M[r] = [x / inv for x in M[r]]
        for i in range(nrow):
            if i != r and M[i][c] != 0:
                f = M[i][c]
                M[i] = [M[i][k] - f * M[r][k] for k in range(nunk)]
        piv[c] = r
        r += 1
    free = [c for c in range(nunk) if c not in piv]
    if len(free) != 1:
        return None
    fc = free[0]
    v = [Fr(0)] * nunk
    v[fc] = Fr(1)
    for c, pr in piv.items():
        v[c] = -M[pr][fc]
    # clear denominators
    from math import gcd
    lcm = 1
    for x in v:
        lcm = lcm * x.denominator // gcd(lcm, x.denominator)
    return [int(x * lcm) for x in v]


def leading_and_branch(coeffs, dy, dF):
    """Print the W-leading coeff (poly in y) and factor it via sympy."""
    import sympy as sp
    y = sp.symbols('y')
    # coeffs indexed [dF*(dy+1) + i] is coeff of W^dF * y^i (top block)
    top = sum(coeffs[dF * (dy + 1) + i] * y**i for i in range(dy + 1))
    print(f"   W^{dF} leading coeff (in y): {sp.factor(top)}", flush=True)
    return sp.factor(top)


def run_depth(name, j, K, fit_hi, dy_range, dF_range, branch=True):
    print(f"\n== {name}", flush=True)
    t = time.time()
    Dp = Dj_mod(j, K, PRIME)                        # D_j(k) mod p, fast
    print(f"   D_j to k={K} (mod p) in {time.time()-t:.1f}s; fit 0..{fit_hi}, "
          f"holdout {fit_hi+1}..{K}", flush=True)
    found = minbox_scan(Dp, K, fit_hi, dy_range, dF_range)
    if not found:
        print("   >>> NO degree-<=%d relation found" % max(dF_range), flush=True)
        return None
    dy, dF, _ = min(found, key=lambda t: (t[1], t[0]))
    print(f"   >>> minimal box (deg_y={dy}, deg_W={dF})", flush=True)
    if not branch:
        return (dy, dF, None)
    t = time.time()
    N = Dj_exact_int(j, K)                          # exact, only at the box K
    print(f"   exact D_j over Q in {time.time()-t:.1f}s (branch fingerprint)",
          flush=True)
    coeffs = exact_solve(N, K, dy, dF)
    if coeffs is None:
        print("   exact solve: nullspace not 1-dim, skipping branch", flush=True)
        return (dy, dF, None)
    lead = leading_and_branch(coeffs, dy, dF)
    return (dy, dF, lead)


def main():
    K = int(sys.argv[1]) if len(sys.argv) > 1 else 110
    holdout = int(sys.argv[2]) if len(sys.argv) > 2 else 16
    depths = [int(x) for x in sys.argv[3].split(',')] if len(sys.argv) > 3 else [2]
    dymax = int(sys.argv[4]) if len(sys.argv) > 4 else 22
    fit_hi = K - holdout
    # stage C: depth 1 must reproduce the (8,4) box (branch fingerprint printed).
    # Fixed K=76 (depth-1 mod-p is ~0.3s) so fit_hi=62 >= the box's 45 unknowns.
    r1 = run_depth("stage C calibration: depth 1 (expect box (8,4))",
                   1, 76, 62, range(4, 15), range(1, 5))
    assert r1 and r1[0] == 8 and r1[1] == 4, f"CALIB FAILED: {r1}"
    print("   calibration OK: depth-1 box (8,4) reproduced", flush=True)

    for j in depths:
        # W4 hypothesis: deg_W <= 4.  Scan wider in deg_y (depth-2 curve is
        # higher degree in y).  branch=False keeps it on the fast mod-p path.
        run_depth(f"depth {j}", j, K, fit_hi, range(4, dymax + 1), range(1, 7),
                  branch=False)


if __name__ == "__main__":
    main()
