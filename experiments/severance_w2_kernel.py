#!/usr/bin/env python3
"""Severance W2: DERIVE the depth-1 minimal polynomial Phi(x, W) by the kernel method.

Nothing here is fitted.  The only inputs are (a) the two-class gap walk defined by
`experiments/depth1_gap_walk.py` (its `transitions` table and its start/end
conventions, all re-read and asserted below) and (b) the assembly identity

    D_1(k) = [y^k]( Phat(y) - B(y)^2 / (3 + S(y)) )                          (II)

of `results/onset-defect-depth1-closed.md` Sec. 2.  No series of D_1 is ever
consulted, no linear system is solved against data, and `PHI_COEFFS` of
`experiments/depth1_recurrence.py` is never imported.

------------------------------------------------------------------ the walk

State (g, c): gap g >= 1 between the pair's two cells, class c in {J, P}.
Reading `transitions` (asserted in stage 0):

  * P-row, g >= 3 (generic): the bulk kernel, steps -2..+2 with weights
    (1,2,3,2,1), staying in class P -- except that a step landing on g' = 1 is
    reclassified J (gp == 1 always joins).
  * J-row, g >= 3 (generic): a *uniform* background 8 -> (1,J), 2 -> (2,J),
    8 -> (2,P), 12 -> (g',P) for every g' >= 3, PLUS the same (1,2,3,2,1) block
    at g' = g+d contributing +k_d to J and -2 k_d to P (folded into J at g'=1).
    The uniform background is the rank-one "long jump" that carries the
    localized eigenvalue rho ~ 14.41.
  * g = 1 and g = 2 rows of both classes are genuine boundary exceptions with
    their own constant tails (asserted verbatim in stage 0).

With u marking the gap, the bulk kernel is K(u) = (1+u+u^2)^2 / u^2, so the
kernel of the walk is

    D(u) = u^2 - y (1+u+u^2)^2,        D(u) = 0  <=>  u = +- s (1+u+u^2),

with s = sqrt(y).  The four roots come in two conjugate pairs; the two small
roots (u ~ +-s) are

    u1 = ((1-s) - A) / (2s),   A = sqrt(1-2s-3s^2) = sqrt((1-3s)(1+s)),
    u2 = (-(1+s) + B) / (2s),  B = sqrt(1+2s-3s^2) = sqrt((1+3s)(1-s)).

The branch point 1-3s = 0, i.e. y = 1/9, i.e. x = 1/27, is the (27x-1) that
runs through Phi.

------------------------------------------------ the functional equation

J(y,u) = sum_m y^m sum_g j_m(g) u^g, likewise P.  J is a polynomial in u at each
order (J-mass only spreads by 2 per step); P has an eventually-constant tail in
g, so P has a simple pole at u = 1 and 1/(1-u) appears throughout.  Writing
J_3 = J - j1 u - j2 u^2, P_3 = P - p2 u^2 (p1 = 0 identically: gp = 1 is always
class J), the step operator gives

  J = J0 + y[ K J_3 - 2 j3 u + Jm(8u+2u^2) + j1(5u+2u^2+u^3)
              + j2(6u+3u^2+2u^3+u^4) + p3 u + p2(2u+2u^2) ]
  P = P0 + y[ K P_3 - p3 u - 2 K J_3 + 2 j3 u
              + Jm(8u^2 + 12u^3/(1-u)) + j1(4u^2+6u^3+8u^4/(1-u))
              + j2(4u^2+6u^3+8u^4+10u^5/(1-u))
              + p2(u^2+4u^3+3u^4+2u^5/(1-u)) ]

with Jm = sum_{g>=3} j(g) = J(y,1) - j1 - j2.  Six unknown series of y:
j1, j2, j3, Jm, p2, p3.  Multiplying the J-equation by u^2 and using
-y(1+u+u^2)^2 = D(u) - u^2 gives

    D(u) J(u) = u^2 Q(u) + D(u) (j1 u + j2 u^2),
    Q(u) = J0(u) - j1 u - j2 u^2 + y R_J(u),

so J(u) = u^2 Q(u)/D(u) + j1 u + j2 u^2 and the six closing equations are

  (1),(2)  Q(u1) = Q(u2) = 0                    [J analytic at the small roots]
  (3)      j1 = [u^1]J0 + y ( j3 + [u^1]R_J )    [self-consistency [u^3]J = j3]
  (4)      Jm (1 - 9y) = Q(1)                    [J at u = 1; K(1) = 9]
  (5),(6)  P0(ui) - p2 ui^2 - 2 ui^2 Q'(ui)/D'(ui) + y R_P(ui) = 0
                                                 [P analytic at the small roots]

That is a 6x6 linear system over Q(s)[A,B]/(A^2-(1-2s-3s^2), B^2-(1+2s-3s^2)),
solved once per start vector (interior and bare).  The end functionals of
`walk_families` then give, with q_end = (4,5,6,6,...) on J and (2,1,0,...) on P
and bare_end = 1 on J:

    S  = y (4 j1 + 5 j2 + 6 Jm + p2)      [interior start]
    B  = 1 + y (4 j1 + 5 j2 + 6 Jm + p2)  [bare start]
    Phat = y (j1 + j2 + Jm)               [bare start]

--------------------------------------------------- eliminating the extension

F1 = Phat - B^2/(3+S) lands as c0 + c1 A + c2 B + c3 AB with ci in Q(s).  The
Galois group of Q(s,A,B) over Q(y) is dihedral of order 8, generated by
A -> -A, B -> -B and sigma: s -> -s with A <-> B; F1 is sigma-invariant (sigma
merely swaps the two small roots), so F1 has degree 4 over Q(y) and

    Phi(T) = ((T-c0)^2 + P)^2 - 4a (c1 (T-c0) + R)^2,
    P = c1^2 a - c2^2 b - c3^2 ab,   R = c2 c3 b,   a = A^2, b = B^2,

is its minimal polynomial (the product over the four cosets, done in closed
form).  Its coefficients come out even in s, i.e. polynomials in y.  Finally
y = 3x and N(x) = sum_k 3^(k+1) D_1(k) x^k = 3 F1(3x) + 1 (the +1 undoes
[y^0](Phat - B^2/(3+S)) = -1/3), so T = (W-1)/3 delivers Phi(x, W).

rho ~ 14.41 is nowhere in the answer: it is the dominant pole of S, B and Phat
separately, and it is killed inside F1 by the rank-one residue cancellation --
here that is automatic, because the elimination never produces the boundary
system whose spectrum rho belongs to.

Run from repo root:  python3 experiments/severance_w2_kernel.py
"""
import os
import sys
import time
from collections import defaultdict

import sympy as sp

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from depth1_gap_walk import transitions                          # noqa: E402

s, x, y, W, tau = sp.symbols('s x y W tau')
AA = 1 - 2 * s - 3 * s ** 2          # A^2
BB = 1 + 2 * s - 3 * s ** 2          # B^2
BULK = {-2: 1, -1: 2, 0: 3, 1: 2, 2: 1}
GCHECK = 24                          # generic rows asserted for 3 <= g <= GCHECK
GPMAX = 45                           # tail depth asserted in the transition table

# The boundary rows, verbatim from `transitions` (asserted in stage 0).
# value = (dict of (g', class) -> weight for the head, uniform tail weight from
#          gap `tail_from` onward, tail class 'P')
BOUNDARY = {
    (1, 'J'): ({(1, 'J'): 5, (2, 'J'): 2, (2, 'P'): 4, (3, 'J'): 1, (3, 'P'): 6}, 4, 8),
    (2, 'J'): ({(1, 'J'): 6, (2, 'J'): 3, (2, 'P'): 4, (3, 'J'): 2, (3, 'P'): 6,
                (4, 'J'): 1, (4, 'P'): 8}, 5, 10),
    (1, 'P'): ({(1, 'J'): 3, (2, 'J'): 2, (2, 'P'): 2, (3, 'P'): 5}, 4, 4),
    (2, 'P'): ({(1, 'J'): 2, (2, 'J'): 2, (2, 'P'): 1, (3, 'P'): 4, (4, 'P'): 3}, 5, 2),
}


# ------------------------------------------------- stage 0: read the walk

def generic_row(g, c):
    """The claimed generic transition row at gap g >= 3, truncated at GPMAX."""
    out = defaultdict(int)
    if c == 'P':
        for d, k in BULK.items():
            gp = g + d
            out[(gp, 'J' if gp == 1 else 'P')] += k
    else:
        out[(1, 'J')] += 8
        out[(2, 'J')] += 2
        out[(2, 'P')] += 8
        for gp in range(3, GPMAX + 1):
            out[(gp, 'P')] += 12
        for d, k in BULK.items():
            gp = g + d
            if gp == 1:
                out[(1, 'J')] += k - 2 * k
            else:
                out[(gp, 'J')] += k
                out[(gp, 'P')] -= 2 * k
    return {a: b for a, b in out.items() if b}


def check_walk():
    for g in range(3, GCHECK + 1):
        for c in 'JP':
            got = transitions(g, c, GPMAX)
            assert got == generic_row(g, c), (g, c)
    for (g, c), (head, tail_from, tw) in BOUNDARY.items():
        want = dict(head)
        for gp in range(tail_from, GPMAX + 1):
            want[(gp, 'P')] = want.get((gp, 'P'), 0) + tw
        assert transitions(g, c, GPMAX) == want, (g, c)
    # start vectors, rebuilt exactly as walk_families does
    dp_int = defaultdict(int)
    for g in range(1, GPMAX + 1):
        for a in range(-1 - g - 1, 3):
            T = (a, a + g)
            if not any(abs(t) <= 1 for t in T):
                continue
            nc = 'J' if (g == 1 or (abs(T[0]) <= 1 and abs(T[1]) <= 1)) else 'P'
            dp_int[(g, nc)] += 1
    want = {(1, 'J'): 4, (2, 'J'): 1, (2, 'P'): 4}
    for g in range(3, GPMAX + 1):
        want[(g, 'P')] = 6
    assert dict(dp_int) == want, dict(dp_int)
    return True


# ------------------------- arithmetic in Q(s)[A,B]/(A^2-AA, B^2-BB), basis 1,A,B,AB

C = sp.cancel
ZERO = (sp.S(0),) * 4
ONE = (sp.S(1), sp.S(0), sp.S(0), sp.S(0))


def K(e):
    return (sp.sympify(e), sp.S(0), sp.S(0), sp.S(0))


def add(z, w):
    return tuple(C(p + q) for p, q in zip(z, w))


def sub(z, w):
    return tuple(C(p - q) for p, q in zip(z, w))


def smul(k, z):
    return tuple(C(k * p) for p in z)


def mul(z, w):
    c0, c1, c2, c3 = z
    d0, d1, d2, d3 = w
    return (C(c0 * d0 + c1 * d1 * AA + c2 * d2 * BB + c3 * d3 * AA * BB),
            C(c0 * d1 + c1 * d0 + c2 * d3 * BB + c3 * d2 * BB),
            C(c0 * d2 + c2 * d0 + c1 * d3 * AA + c3 * d1 * AA),
            C(c0 * d3 + c3 * d0 + c1 * d2 + c2 * d1))


def conjA(z):
    return (z[0], -z[1], z[2], -z[3])


def inv(z):
    t = mul(z, conjA(z))                       # kills the A and AB parts
    assert t[1] == 0 and t[3] == 0
    e0, e2 = t[0], t[2]
    d = C(e0 ** 2 - e2 ** 2 * BB)
    u = mul(conjA(z), (e0, sp.S(0), -e2, sp.S(0)))
    return tuple(C(p / d) for p in u)


def div(z, w):
    return mul(z, inv(w))


def pw(u, n):
    r = ONE
    for _ in range(n):
        r = mul(r, u)
    return r


def poly(u, coeffs):
    r, p = ZERO, ONE
    for c in coeffs:
        r = add(r, mul(c, p))
        p = mul(p, u)
    return r


U1 = (C((1 - s) / (2 * s)), C(-1 / (2 * s)), sp.S(0), sp.S(0))
U2 = (C(-(1 + s) / (2 * s)), sp.S(0), C(1 / (2 * s)), sp.S(0))
Y = K(s ** 2)


def check_roots():
    for u in (U1, U2):
        oo = add(add(ONE, u), mul(u, u))
        d = sub(mul(u, u), mul(Y, mul(oo, oo)))
        assert all(sp.simplify(c) == 0 for c in d), d
    return True


# ------------------------------------------- the 6 x 6 system, one start vector

def equations(X, J0c, P0fn, J0_1):
    """The six closing conditions, linear in X = (j1, j2, j3, Jm, p2, p3)."""
    j1, j2, j3, Jm, p2, p3 = X
    # R_J(u) = c1 u + c2 u^2 + c3 u^3 + c4 u^4
    c1 = add(add(smul(-2, j3), smul(8, Jm)),
             add(add(smul(5, j1), smul(6, j2)), add(p3, smul(2, p2))))
    c2 = add(add(smul(2, Jm), smul(2, j1)), add(smul(3, j2), smul(2, p2)))
    c3 = add(j1, smul(2, j2))
    c4 = j2
    RJ = [ZERO, c1, c2, c3, c4]
    RJp = [c1, smul(2, c2), smul(3, c3), smul(4, c4)]
    J0 = [K(v) for v in J0c]
    J0p = [K((i + 1) * J0c[i + 1]) for i in range(len(J0c) - 1)]

    def Q(u):
        return sub(add(poly(u, J0), mul(Y, poly(u, RJ))),
                   add(mul(j1, u), mul(j2, mul(u, u))))

    def Qp(u):
        return sub(add(poly(u, J0p), mul(Y, poly(u, RJp))),
                   add(j1, smul(2, mul(j2, u))))

    def Dp(u):
        oo = add(add(ONE, u), mul(u, u))
        return sub(smul(2, u), smul(2, mul(Y, mul(oo, add(ONE, smul(2, u))))))

    def RP(u):
        iu = inv(sub(ONE, u))
        t = mul(sub(smul(2, j3), p3), u)
        t = add(t, mul(Jm, add(smul(8, pw(u, 2)), mul(smul(12, pw(u, 3)), iu))))
        t = add(t, mul(j1, add(add(smul(4, pw(u, 2)), smul(6, pw(u, 3))),
                               mul(smul(8, pw(u, 4)), iu))))
        t = add(t, mul(j2, add(add(smul(4, pw(u, 2)),
                                   add(smul(6, pw(u, 3)), smul(8, pw(u, 4)))),
                               mul(smul(10, pw(u, 5)), iu))))
        t = add(t, mul(p2, add(add(pw(u, 2), add(smul(4, pw(u, 3)),
                                                 smul(3, pw(u, 4)))),
                               mul(smul(2, pw(u, 5)), iu))))
        return t

    out = [Q(U1), Q(U2),
           sub(sub(j1, K(J0_1)), mul(Y, add(j3, c1))),
           sub(mul(Jm, sub(ONE, smul(9, Y))), Q(K(1)))]
    for u in (U1, U2):
        shift = div(mul(pw(u, 2), Qp(u)), Dp(u))
        out.append(add(sub(sub(P0fn(u), mul(p2, pw(u, 2))), smul(2, shift)),
                       mul(Y, RP(u))))
    return out


def solve_start(J0c, P0fn, J0_1):
    rhs = [smul(-1, e) for e in equations([ZERO] * 6, J0c, P0fn, J0_1)]
    cols = []
    for k in range(6):
        e = [ZERO] * 6
        e[k] = ONE
        cols.append([add(v, r) for v, r in zip(equations(e, J0c, P0fn, J0_1), rhs)])
    n = 6
    M = [[cols[c][r] for c in range(n)] + [rhs[r]] for r in range(n)]
    for c in range(n):
        piv = next(r for r in range(c, n) if any(t != 0 for t in M[r][c]))
        M[c], M[piv] = M[piv], M[c]
        iv = inv(M[c][c])
        M[c] = [mul(iv, e) for e in M[c]]
        for r in range(n):
            if r != c and any(t != 0 for t in M[r][c]):
                f = M[r][c]
                M[r] = [sub(M[r][j], mul(f, M[c][j])) for j in range(n + 1)]
    return [M[r][n] for r in range(n)]


def J0_P0(kind):
    if kind == 'int':                       # dp_int: J = 4u + u^2, P = 4u^2 + 6u^3/(1-u)
        return ([0, 4, 1],
                lambda u: add(smul(4, pw(u, 2)),
                              mul(smul(6, pw(u, 3)), inv(sub(ONE, u)))),
                4)
    return ([0, 1], lambda u: mul(pw(u, 2), inv(sub(ONE, u))), 1)  # dp_bare


# ------------------------------------------------------------------- assembly

def build_F1():
    Xi = solve_start(*J0_P0('int'))
    Xb = solve_start(*J0_P0('bare'))
    q = lambda X: add(add(smul(4, X[0]), smul(5, X[1])),
                      add(smul(6, X[3]), X[4]))
    S = mul(Y, q(Xi))
    B = add(ONE, mul(Y, q(Xb)))
    Ph = mul(Y, add(add(Xb[0], Xb[1]), Xb[3]))
    return sub(Ph, div(mul(B, B), add(K(3), S))), S, B, Ph


def minpoly_from_F1(F1):
    c = [C(e) for e in F1]
    den = sp.lcm([sp.fraction(sp.together(ci))[1] for ci in c])
    n0, n1, n2, n3 = [sp.expand(C(ci * den)) for ci in c]
    P = sp.expand(n1 ** 2 * AA - n2 ** 2 * BB - n3 ** 2 * AA * BB)
    Psi = sp.expand(((tau - n0) ** 2 + P) ** 2
                    - 4 * AA * (n1 * (tau - n0) + n2 * n3 * BB) ** 2)
    cs = sp.Poly(Psi, tau).all_coeffs()          # tau^4 .. tau^0
    cT = [sp.expand(cs[4 - k] * den ** k) for k in range(5)]
    g = sp.gcd(cT)
    cT = [sp.expand(C(ci / g)) for ci in cT]
    cY = []
    for ci in cT:                                # must be even in s
        out = 0
        for (k,), co in sp.Poly(ci, s).as_dict().items():
            assert k % 2 == 0, ("odd power of s survived", k)
            out += co * y ** (k // 2)
        cY.append(sp.expand(out))
    # y = 3x and N(x) = 3 F1(3x) + 1, i.e. T = (W-1)/3
    Phi = sum(cY[k].subs(y, 3 * x) * ((W - 1) / sp.Integer(3)) ** k for k in range(5))
    p = sp.Poly(sp.expand(Phi), W)
    cs = [sp.expand(p.coeff_monomial(W ** k)) for k in range(5)]
    den = sp.lcm([sp.fraction(sp.together(ci))[1] for ci in cs])
    cs = [sp.expand(C(ci * den)) for ci in cs]
    g = sp.gcd(cs)
    return [sp.expand(C(ci / g)) for ci in cs]


_CACHE = []


def derived_phi():
    """Coefficients of W^0 .. W^4 of the derived minimal polynomial Phi(x, W)."""
    if not _CACHE:
        check_walk()
        check_roots()
        F1, _, _, _ = build_F1()
        _CACHE.extend(minpoly_from_F1(F1))
    return list(_CACHE)


def main():
    t0 = time.time()
    stamps = []

    def stage(name):
        stamps.append((name, time.time() - t0))
        print(f"  [{stamps[-1][1]:7.2f}s] {name}")

    print("== stage 0: re-read the gap walk from depth1_gap_walk.transitions")
    check_walk()
    stage(f"generic rows g=3..{GCHECK}, boundary rows g=1,2, start vectors verified")

    print("== stage 1: kernel D(u) = u^2 - y(1+u+u^2)^2, small roots u1, u2")
    check_roots()
    stage("u1 = ((1-s)-A)/2s, u2 = (-(1+s)+B)/2s satisfy D(u) = 0 exactly")

    print("== stage 2: solve the 6x6 boundary system (interior start)")
    Xi = solve_start(*J0_P0('int'))
    stage("j1, j2, j3, Jm, p2, p3 over Q(s)[A,B]")

    print("== stage 3: solve the 6x6 boundary system (bare start)")
    Xb = solve_start(*J0_P0('bare'))
    stage("j1, j2, j3, Jm, p2, p3 over Q(s)[A,B]")

    print("== stage 4: end functionals -> S, B, Phat; identity (II) -> F_1")
    q = lambda X: add(add(smul(4, X[0]), smul(5, X[1])),
                      add(smul(6, X[3]), X[4]))
    S = mul(Y, q(Xi))
    B = add(ONE, mul(Y, q(Xb)))
    Ph = mul(Y, add(add(Xb[0], Xb[1]), Xb[3]))
    F1 = sub(Ph, div(mul(B, B), add(K(3), S)))
    stage("F_1 = c0 + c1 A + c2 B + c3 AB, ci in Q(s)")
    for i, nm in enumerate(('c0', 'c1', 'c2', 'c3')):
        print(f"     {nm} = {sp.factor(F1[i])}")

    print("== stage 5: eliminate A, B (norm over the order-8 Galois group)")
    coeffs = minpoly_from_F1(F1)
    stage("Phi(x, W), coefficients of W^0..W^4")
    for k, c in enumerate(coeffs):
        print(f"     W^{k}: {sp.factor(c)}")

    print()
    print("stage timings")
    prev = 0.0
    for name, t in stamps:
        print(f"  {t - prev:7.2f}s  {name}")
        prev = t
    print(f"  {prev:7.2f}s  total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
