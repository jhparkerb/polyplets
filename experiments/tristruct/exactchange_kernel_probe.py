#!/usr/bin/env python3
"""Exact Change probe 3: the kernel, in two layers.

Context: results/exactchange-probes.md.  The GF(2) observability quotient of
the strip functional has rank r(H) = A034299(H-1); the state space has
Motzkin(H+1)-1 states but only N(H) = 8, 19, 43, 101, 239 (H=4..8) distinct
phi values (Nerode classes).  So the kernel of phi splits:

  layer 1 (states -> classes): weight-2 relations s + t, s ~ t.  Dimension
     n - N.  The hunt: a combinatorial invariant computing the class of a
     state a priori.  Candidates tested here include run-collapse keys
     (collapse maximal occupied/empty row-runs -- each occupied run is one
     block, so a state is an alternating run pattern plus a partition of the
     occupied runs; A000975 counts alternating patterns, the standing scent).
  layer 2 (classes -> rank): dimension N - r.  The hunt: low-weight GF(2)
     relations among class representatives (the CKN "uncrossing" shape --
     for matchings the kernel is generated by weight-3 planarity relations).
     We enumerate weight-3 and weight-4 relations among the N distinct phi
     values and check whether they span.

Fail-closed: rank must equal A034299 exactly; phi must separate accept;
Nerode counts at H=4..8 must equal the banked probe-1 values.
"""
import sys
import time
from collections import defaultdict

from r3_inv_rank_probe import build_automaton
from exactchange_phi_probe import obs_basis_gf2, a034299, classes_by

BANKED_NERODE = {4: 8, 5: 19, 6: 43, 7: 101, 8: 239}


def compute_phi(order, delta, accept):
    n = len(order)
    vecs = obs_basis_gf2(delta, accept)
    r = len(vecs)
    pad = (-n) % 8
    phi = [0] * n
    for i, v in enumerate(vecs):
        for s in range(n):
            if v >> (s + pad) & 1:
                phi[s] |= 1 << i
    acc = {phi[s] for s in range(n) if accept[s]}
    rej = {phi[s] for s in range(n) if not accept[s]}
    assert not (acc & rej), "phi fails to separate accept"
    return phi, r


def runs(st):
    """State tuple -> list of (block_id_or_-1, length) maximal row-runs.
    Every occupied run is a single block (vertically adjacent cells merge)."""
    out = []
    for v in st:
        b = v if v >= 0 else -1
        if out and out[-1][0] == b:
            out[-1][1] += 1
        else:
            out.append([b, 1])
    return [(b, ln) for b, ln in out]


def canon_blocks(tokens):
    """Relabel block ids in first-appearance order; -1 stays."""
    seen, out = {}, []
    for t in tokens:
        if t == -1:
            out.append(-1)
        else:
            if t not in seen:
                seen[t] = len(seen)
            out.append(seen[t])
    return tuple(out)


def key_collapse(st, cap):
    """Run pattern with lengths capped at `cap`, block partition kept."""
    toks = []
    for b, ln in runs(st):
        toks.extend([b] * min(ln, cap))
    return canon_blocks(toks)


def key_parity(st):
    """Run pattern with lengths reduced mod 2 (1 or 2 tokens)."""
    toks = []
    for b, ln in runs(st):
        toks.extend([b] * (2 - ln % 2))
    return canon_blocks(toks)


def gf2_rank(rows):
    basis = {}
    for row in rows:
        while row:
            p = row.bit_length() - 1
            if p in basis:
                row ^= basis[p]
            else:
                basis[p] = row
                break
    return len(basis)


def main():
    hs = [int(a) for a in sys.argv[1:]] or list(range(4, 11))
    for H in hs:
        t0 = time.time()
        order, delta, accept, masks = build_automaton(H)
        n = len(order)
        phi, r = compute_phi(order, delta, accept)
        assert r == a034299(H), f"H={H}: rank {r} != A034299 {a034299(H)}"

        # ---- layer 1: Nerode classes ----
        classes = defaultdict(list)
        for s in range(n):
            classes[phi[s]].append(s)
        N = len(classes)
        if H in BANKED_NERODE:
            assert N == BANKED_NERODE[H], f"H={H}: nerode {N} != banked"
        sizes = sorted((len(v) for v in classes.values()), reverse=True)
        nzero = len(classes.get(0, []))
        print(f"H={H} states={n} rank={r} nerode={N}  "
              f"kernel: layer1 dim {n - N}, layer2 dim {N - r}")
        print(f"  class sizes: max={sizes[0]} singletons="
              f"{sum(1 for x in sizes if x == 1)} phi=0 states={nzero}")

        def nsets(st):
            """Multiset of block neighborhoods N(b) = rows(b) expanded +-1.
            The transition rule reads NOTHING else about a block: new cell r
            attaches to b iff r in N(b); b strands iff mask misses N(b).  So
            this is a congruence over every field -- the question is whether
            it is EXACTLY the GF(2) Nerode partition."""
            blocks = defaultdict(set)
            for row, v in enumerate(st):
                if v >= 0:
                    for d in (-1, 0, 1):
                        if 0 <= row + d < len(st):
                            blocks[v].add(row + d)
            return tuple(sorted(tuple(sorted(b)) for b in blocks.values()))

        cands = [
            ("N(b) multiset",
             [nsets(order[s]) for s in range(n)]),
            ("N(b) set (deduped)",
             [tuple(sorted(set(nsets(order[s])))) for s in range(n)]),
            ("collapse cap=1",
             [key_collapse(order[s], 1) for s in range(n)]),
            ("collapse cap=2",
             [key_collapse(order[s], 2) for s in range(n)]),
            ("run-length parity",
             [key_parity(order[s]) for s in range(n)]),
            ("cap=1 + popc%2",
             [(key_collapse(order[s], 1),
               sum(1 for v in order[s] if v >= 0) % 2) for s in range(n)]),
            ("parity + ends",
             [(key_parity(order[s]), order[s][0] >= 0, order[s][-1] >= 0)
              for s in range(n)]),
        ]
        for name, keys in cands:
            k, split, maxper, cls = classes_by(keys, phi)
            verdict = ("EXACT" if split == 0 and k == N else
                       "sound refinement" if split == 0 else
                       f"INCOMPLETE (split={split}, maxper={maxper})")
            print(f"  L1 {name:22s} keys={k:6d}  {verdict}")

        # ---- layer 2: relations among class representatives ----
        reps = sorted(classes)          # the N distinct phi values
        idx = {v: i for i, v in enumerate(reps)}
        rel_rows = []
        w3 = []
        w4_quads = []
        for i in range(N):
            for j in range(i + 1, N):
                x = reps[i] ^ reps[j]
                k = idx.get(x)
                if k is not None and k > j:
                    w3.append((i, j, k))
                    rel_rows.append((1 << i) | (1 << j) | (1 << k))
        d3 = gf2_rank(list(rel_rows))
        need = N - r - (1 if 0 in idx else 0)
        line = f"  L2 weight-3 relations: {len(w3)} found, span dim {d3} / need {need}"
        if d3 < need:
            # weight-4 via pair-sum collisions
            pair_sum = defaultdict(list)
            for i in range(N):
                for j in range(i + 1, N):
                    pair_sum[reps[i] ^ reps[j]].append((i, j))
            n4 = 0
            for v, ps in pair_sum.items():
                if len(ps) < 2:
                    continue
                for a in range(len(ps)):
                    for b in range(a + 1, len(ps)):
                        s = set(ps[a]) | set(ps[b])
                        if len(s) == 4:
                            rel_rows.append(sum(1 << x for x in s))
                            w4_quads.append(tuple(sorted(s)))
                            n4 += 1
            d4 = gf2_rank(list(rel_rows))
            line += f"; +weight-4 ({n4}): span dim {d4}"
        print(line)

        if H <= 5:
            print("  classes (members as state tuples):")
            for v in reps:
                mem = classes[v]
                tag = " *phi=0*" if v == 0 else ""
                print(f"    [{len(mem)}]{tag} " +
                      " | ".join(str(order[s]) for s in mem[:6]) +
                      (" ..." if len(mem) > 6 else ""))
            if w3:
                print("  weight-3 triples (rep states):")
                for i, j, k in w3[:12]:
                    print(f"    {order[classes[reps[i]][0]]} + "
                          f"{order[classes[reps[j]][0]]} + "
                          f"{order[classes[reps[k]][0]]} = 0")
            if w4_quads:
                print("  weight-4 quads (rep states):")
                for q in w4_quads[:12]:
                    print("    " + " + ".join(
                        str(order[classes[reps[i]][0]]) for i in q) + " = 0")
        print(f"  ({time.time()-t0:.1f}s)", flush=True)
    return 0


if __name__ == '__main__':
    sys.exit(main())
